# Generates rust/src/tables.rs, the code-point ranges of Python's str.isspace, str.isalnum (plus '_': what `\w` matches) and str.isdecimal (what `\d` matches), from the running interpreter's unicodedata; no inputs; output: rust/src/tables.rs. Run: python3 -I rust/gen_tables.py > rust/src/tables.rs
import sys, unicodedata


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(chr(c)):
            if start is None:
                start = c
            last = c
        elif start is not None:
            out.append((start, last))
            start = None
    if start is not None:
        out.append((start, last))
    return out


def emit(name, doc, rs):
    print("/// %s" % doc)
    print("pub(crate) static %s: &[(u32, u32)] = &[" % name)
    for i in range(0, len(rs), 6):
        print("    " + " ".join("(0x%X, 0x%X)," % r for r in rs[i:i + 6]))
    print("];\n")


print("//! Code-point range tables generated by `rust/gen_tables.py` from Python %s (Unicode %s); do not edit.\n" % (sys.version.split()[0], unicodedata.unidata_version))
emit("SPACE", "Code points for which Python's `str.isspace()` is true (the `\\s` of `re` and what `strip()` and `split()` remove).", ranges(str.isspace))
emit("WORD", "Code points that `re`'s `\\w` matches in a `str` pattern: `str.isalnum()` or `_`.", ranges(lambda ch: ch.isalnum() or ch == "_"))
emit("DIGIT", "Code points that `re`'s `\\d` matches in a `str` pattern (`str.isdecimal()`).", ranges(str.isdecimal))
